def _fold(text: str) -> str:
    """Lowercase, without accents, for keyword matching in several languages."""
    text = unicodedata.normalize("NFKD", text.lower())
    return "".join(c for c in text if not unicodedata.combining(c)).replace("’", "'")


def resolve_icon(name: str) -> Optional[str]:
    key = name.strip().lower().replace("_", "-")
    if key in ICONS:
        return key
    if key in ALIASES:
        return ALIASES[key]
    if key.endswith("s") and key[:-1] in ICONS:
        return key[:-1]
    if key.endswith("s") and key[:-1] in ALIASES:
        return ALIASES[key[:-1]]
    return None


