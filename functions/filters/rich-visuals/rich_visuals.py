def _words(text: str) -> list[str]:
    return re.findall(r"[a-z0-9']+|a\+", text)


def classify(text: str) -> dict:
    """What to do for one message: skip it, answer in rich text, or answer with a visual. Pure, so it is easy to test."""
    folded = _fold(text).strip()
    result = {"mode": "skip", "topics": [], "icons": [], "emoji": bool(WANTS_EMOJI.search(folded)), "reason": ""}
    if not folded:
        result["reason"] = "empty"
        return result
    if PLAIN.search(folded):
        result["reason"] = "asked for plain text"
        return result
    words = _words(EMOJI_RUN_RE.sub(" ", folded))
    if not words:
        result["reason"] = "only emoji or punctuation"
        return result
    if len(words) <= 8 and all(w in SMALLTALK or w in FILLER for w in words) and any(w in SMALLTALK for w in words):
        result["reason"] = "greeting, thanks or small talk"
        return result
    topics = [(name, visual, icons) for name, visual, rx, icons in _TOPIC_RES if rx.search(folded)]
    wants_visual = bool(WANTS_VISUAL.search(folded))
    if len(words) <= 2 and not topics and not wants_visual and "?" not in folded:
        result["reason"] = "too short to need anything"
        return result
    icons: list[str] = []
    for _, _, topic_icons in topics:
        icons += topic_icons
    icons += BASE_ICONS
    result["icons"] = list(dict.fromkeys(i for i in icons if i in ICONS))
    result["topics"] = [name for name, _, _ in topics]
    result["mode"] = "visual" if wants_visual or any(visual for _, visual, _ in topics) else "rich"
    result["reason"] = "asked for a visual" if wants_visual else ("topic: " + ", ".join(result["topics"]) if topics else "a substantive message")
    return result


