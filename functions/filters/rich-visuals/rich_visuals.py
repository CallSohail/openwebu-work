def resolve_loose(name: str) -> Optional[str]:
    """An icon from a name a model made up: 'icon-weather-sunny' -> sun, 'battery-check' -> battery, 'fa-sun' -> sun."""
    key = resolve_icon(name)
    if key:
        return key
    parts = [p for p in re.split(r"[-_\s]+", name.lower()) if p and p not in GENERIC_PARTS and not p.isdigit()]
    for size in range(len(parts), 0, -1):
        for start in range(0, len(parts) - size + 1):
            key = resolve_icon("-".join(parts[start:start + size]))
            if key:
                return key
    return None


def icon_svg(name: str, label: str = "") -> str:
    """The inline SVG for an icon, or '' when there is no such icon."""
    key = resolve_loose(name)
    if not key:
        return ""
    label = re.sub(r"[^\w .,:%()+-]", "", label, flags=re.UNICODE).strip()[:60]
    a11y = f"role='img' aria-label='{label}'" if label else "aria-hidden='true' focusable='false'"
    return SVG_OPEN.format(name=key, a11y=a11y) + ICONS[key] + "</svg>"


def _emoji_to_icons(text: str) -> str:
    """Inside a visual: each emoji that stands for something becomes its icon; the rest are dropped."""

    def swap(match: re.Match) -> str:
        run = match.group(0)
        out = []
        for char in run:
            if char in EMOJI_ICONS:
                out.append(icon_svg(EMOJI_ICONS[char]))
        return "".join(out)

    return EMOJI_RUN_RE.sub(swap, text)


